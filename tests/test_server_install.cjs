'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const env={};env.globalThis=env;
vm.runInNewContext(fs.readFileSync('js/os-catalog.js','utf8'),env);
vm.runInNewContext(fs.readFileSync('js/audit-server-install.js','utf8'),env);
vm.runInNewContext(fs.readFileSync('js/audit-field-renderer.js','utf8'),env);
const catalog=env.AuditOSCatalog,install=env.RabbitMoleServerInstall,field=env.RabbitMoleFieldRenderer;
assert(catalog.SERVER_PRESETS.includes('Windows Server 2025 Standard'));
assert(catalog.SERVER_PRESETS.includes('Ubuntu Server 24.04 LTS'));
assert(catalog.SERVER_PRESETS.includes('Debian 13 (Trixie)'));
assert(install.isServer('Servidor físico')&&install.isServer('Servidor virtual'));
assert(!install.isServer('Estación de trabajo'));
const html=s=>String(s??'').replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;');
const deps={html,str:v=>String(v??''),identifiers:{isLockedField:()=>false},assist:{suggestions:()=>[],assetChoices:()=>[],candidates:()=>[]},state:{},osCatalog:catalog,vendorModels:{},routerModels:{},networkDevices:null,glossary:null,glossaryHelpIcon:''};
const server={_key:'server-1',type:'Servidor físico',os:'Ubuntu Server 24.04 LTS'};
let form=field.render(server,'assets',['os','Sistema operativo','picker',[]],0,deps);
assert(form.includes('<optgroup label="Ubuntu y Debian">'));
assert(form.includes('Ubuntu Server 24.04 LTS" selected'));
assert(form.includes('data-preset="true"'));
assert(!form.includes('Servidor 2025" selected'));
const unknown=field.render({...server,os:'CustomOS 1.0'},'assets',['os','Sistema operativo','picker',[]],0,deps);
assert(unknown.includes('value="__custom__" selected'));
assert(unknown.includes('value="CustomOS 1.0"'));
const workstation=field.render({type:'Portátil',os:'Debian 13'},'assets',['os','Sistema operativo','picker',[]],0,deps);
assert(workstation.includes('<datalist'));
const panel=install.render(server,0,(r,b,d)=>field.render(r,b,d,0,deps),html);
assert(panel.includes('Instalación y función del servidor'));
assert(!install.render({type:'Router'},0,()=>'',html));
assert.equal(install.FIELDS.length,6);
const index=fs.readFileSync('index.html','utf8'),sw=fs.readFileSync('sw.js','utf8');
assert(index.indexOf('js/audit-server-install.js')<index.indexOf('js/app.js'));
assert(sw.includes('./js/audit-server-install.js'));
console.log('PASS server OS choices, custom retention, basic installation and offline preload');
