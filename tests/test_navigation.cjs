'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const app=read('js/app.js'),html=read('index.html'),css=read('css/styles.css'),sw=read('sw.js');
assert(app.includes("if(['records','backups','online','settings','connections','glossary'].includes(section)||section==='intake'||nav.some"),'Glossary must be an allowed destination');
assert(app.includes("page==='glossary'?renderGlossary()"),'Glossary must render');
assert(app.includes("button.classList.toggle('active',active)"),'Active main-menu navigation required');
assert(app.includes('window.history.pushState')&&app.includes('window.addEventListener("popstate"'),'Browser history must restore glossary origin');
assert(app.includes('restoreGlossaryOrigin')&&app.includes('origin.field'),'Field return context required');
assert(html.includes('id="glossary-quick-dialog"'),'Missing contextual glossary dialog');
assert(app.includes('openQuickGlossary')&&app.includes('closeQuickGlossary'),'Contextual help must preserve workspace');
assert(app.includes('closeQuickGlossary(false);'),'Route changes should dismiss quick help');
const glossaryCss=read('css/glossary.css');
assert(glossaryCss.includes('.glossary-quick-dialog[open]')&&glossaryCss.includes('max-width:700px'),'Adaptive glossary drawer missing');
for(const page of ['records','backups','settings','connections','glossary'])assert(html.includes('data-go="'+page+'"'),'Missing '+page);
assert((html.match(/class="nav-icon"/g)||[]).length===5,'Expected five SVG icons');
assert(!/<span class="nav-mark">/.test(html),'Global menu must not use font glyphs');
assert(css.includes('#global-navigation button .nav-icon'),'SVG sizing must be defined');
require('./support/sw-contract.js').assertCached('js/app.js');
console.log('PASS glossary navigation, five sharp SVG icons and PWA cache');

assert(app.includes('glossaryHelpIcon')&&app.includes('refreshRouterModel'),'Unified field help and dependent router model expected');
assert(html.includes('js/router-catalog.js')&&sw.includes('./js/router-catalog.js'),'Router catalog must be available offline');
