'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const crypto=require('node:crypto').webcrypto;
const ctx={TextDecoder,Uint8Array,btoa,atob,crypto,Blob};ctx.globalThis=ctx;
vm.runInNewContext(fs.readFileSync('js/pdf-appendices.js','utf8'),ctx);
const p=ctx.RabbitMolePdfAppendices;
(async()=>{
 const content=new TextEncoder().encode('%PDF-1.4\n1 0 obj\n<<>>\nendobj\ntrailer\n<<>>\n%%EOF\n');
 const file={name:'anexo.pdf',type:'application/pdf',size:content.length,arrayBuffer:async()=>content.buffer};
 const item=await p.fromFile(file);
 assert.equal(item.size,content.length);
 assert.equal(item.sha256.length,64);
 assert.equal(p.normalize([item]).length,1);
 const wifi=await p.fromFile(file,{category:'wifi-analysis',source:'Herramienta externa',observedAt:'2026-10-16'});
 assert.equal(p.normalize([wifi])[0].category,'wifi-analysis');
 assert.equal(p.normalize([wifi])[0].source,'Herramienta externa');
 assert.equal(p.normalize([wifi])[0].observedAt,'2026-10-16');
 assert.equal(p.normalize([item])[0].category,'general');
 assert.throws(()=>p.normalize([{...wifi,category:'javascript'}]),/Categoría/);
 assert.equal((await p.asBlob(item).arrayBuffer()).byteLength,content.length);
 assert.throws(()=>p.normalize([item,item]),/duplicado/);
 assert.throws(()=>p.normalize([{...item,data:btoa('not a pdf'),size:9}]),/cabecera PDF/);
 await assert.rejects(p.fromFile({...file,name:'malware.exe'}),/PDF válido/);
 const html=fs.readFileSync('index.html','utf8'),sw=fs.readFileSync('sw.js','utf8'),app=fs.readFileSync('js/app.js','utf8'),actions=fs.readFileSync('js/audit-actions.js','utf8'),views=fs.readFileSync('js/audit-workflow-views.js','utf8');
 assert(html.includes('js/pdf-appendices.js'));
 assert(sw.includes('./js/pdf-appendices.js'));
 for(const token of ['renderPdfAppendices()','pdfAppendices.normalize(raw.pdfAppendices)','pdf-appendix-upload'])assert(app.includes(token),token);
 assert(app.includes('renderExternalNetworkAnalysis()')&&app.includes('external-network-files'));
 assert(app.includes('renderAppendixActions(item,readonly)'));
 for(const token of ['data-pdf-appendix-download','data-pdf-appendix-remove','data-pdf-appendix-save'])assert(views.includes(token),token);
 assert(actions.includes('dataset.pdfAppendixRemove')&&actions.includes('dataset.pdfAppendixSave'));
 assert(sw.includes('./js/audit-actions.js'));
 assert(html.includes('js/audit-actions.js'));
 assert(!app.includes('dataset.pdfAppendixEdit'),'Obsolete prompt-based PDF editor must be removed');
 console.log('PASS bounded offline PDF appendices, recovery, SHA-256 and UI integration');
})().catch(e=>{console.error(e);process.exitCode=1});
