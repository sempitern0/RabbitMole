'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ctx={Date};ctx.globalThis=ctx;
vm.runInNewContext(fs.readFileSync('js/audit-mitigation.js','utf8'),ctx);
const m=ctx.AuditMitigation;
assert(m.TEMPLATES.length>=8);
assert.equal(m.normalize(undefined).length,0);
const initial=m.fromTemplate('router-services','action-1',{owner:'Administración TI',deadline:'2026-12-12'});
assert.equal(initial.status,'proposed');
assert(initial.steps.length>30);
assert.throws(()=>m.save(initial,{status:'applied'}),/Transición/);
const proposal=m.save(initial,{status:'proposed'});
const approved=m.save(proposal,{status:'approved',approvedBy:'Responsable',approvalDate:'2026-10-16'});
assert.equal(approved.status,'approved');
assert.throws(()=>m.save(approved,{status:'applied'}),/Registra/);
const applied=m.save(approved,{status:'applied',executedBy:'Administrador',executedAt:'2026-10-16',
  changeNotes:'Cambio aplicado durante la ventana autorizada y probado por administrador'});
assert.equal(applied.status,'applied');
assert.throws(()=>m.save(applied,{status:'proposed'}),/Transición/);
assert.equal(m.metrics([{mitigationActions:[applied]}]).applied,1);
assert.equal(m.verification({status:'Abierto',retests:[]},applied),'awaiting-retest');
assert.equal(m.verification({status:'Cerrado',retests:[{date:'2026-10-15',result:'verified'}]},applied),'awaiting-retest');
assert.equal(m.verification({status:'Cerrado',retests:[{date:'2026-10-17',result:'verified'}]},applied),'finding-verified');
assert.equal(m.verification({status:'Abierto',retests:[{date:'2026-10-17',result:'pending'}]},applied),'finding-persists');
assert.equal(m.verification({status:'Abierto',retests:[{date:'2026-10-17',result:'unverified'}]},applied),'inconclusive');
assert.equal(m.verification({status:'Cerrado',retests:[{date:'2026-10-17',result:'verified'}]},approved),'not-applicable');

const checked=m.recordVerification(applied,{date:'2026-10-17',result:'verified',by:'Auditora',notes:'Se ha repetido la prueba de acceso y confirmado el resultado.'},[],()=> 'check-1');
assert.equal(checked.checks.length,1);
assert.equal(m.verification({status:'Abierto',retests:[]},checked),'action-verified');
assert.throws(()=>m.recordVerification(approved,{date:'2026-10-17',result:'verified',by:'Auditora',notes:'Intento de verificar un cambio no aplicado'},[],()=> 'check-2'),/tras aplicar/);
assert.throws(()=>m.recordVerification(applied,{date:'2026-10-15',result:'verified',by:'Auditora',notes:'Prueba anterior al cambio'},[],()=> 'check-2'),/no puede preceder/);
assert.throws(()=>m.save(checked,{checks:[]}),/no se puede editar/);
assert.throws(()=>m.save(checked,{steps:'Nuevo procedimiento no validado'}),/conserva/);
assert.equal(m.normalize(JSON.parse(JSON.stringify([checked])))[0].checks[0].id,'check-1');
assert.throws(()=>m.recordVerification(checked,{date:'2026-10-18',result:'failed',by:'Auditora',notes:'Medida ineficaz tras repetir las comprobaciones'},[],()=> 'check-1'),/duplicado/);
const failed=m.recordVerification(checked,{date:'2026-10-18',result:'failed',by:'Auditora',notes:'La medida no cumple el criterio esperado de seguridad.'},[],()=> 'check-2');
assert.equal(m.verification({},failed),'action-failed');
const residual=m.recordResidual({severity:'Alta'},{level:'Media',decision:'monitor',assessedBy:'Auditora',assessedAt:'2026-10-16',nextReview:'2026-11-16',rationale:'Se revisó el entorno y persiste una exposición limitada.'},[],()=> 'res-1');
assert.equal(residual.length,1);
assert.equal(m.latestResidual({residualAssessments:residual}).level,'Media');
assert.equal(m.normalizeResidual(JSON.parse(JSON.stringify(residual)))[0].id,'res-1');
assert.throws(()=>m.recordResidual({residualAssessments:residual},{level:'Media',decision:'monitor',assessedBy:'Auditora',assessedAt:'2026-10-16',rationale:'Una reevaluación documentada en el expediente.'},[],()=> 'res-1'),/duplicado/);
assert.throws(()=>m.recordResidual({}, {level:'Alta',decision:'monitor',assessedBy:'Auditora',assessedAt:'2026-10-16',rationale:'Exposición documentada.',evidenceKey:'missing'},[],()=> 'res-2'),/evidencia/);
const portfolio=m.portfolio([{_key:'finding-1',id:'FND-1',mitigationActions:[{...initial,deadline:'2026-10-15'}],residualAssessments:residual}], '2026-10-16');
assert.equal(portfolio.counts.overdue,1);
assert.equal(portfolio.counts.residualAssessed,1);
assert.equal(portfolio.counts.residualHigh,0);
assert.equal(portfolio.overdue[0].findingId,'FND-1');
assert.equal(m.portfolio([{mitigationActions:[applied]}],'2026-10-16').counts.unchecked,1);
assert.equal(m.portfolio([{mitigationActions:[failed]}],'2026-10-16').counts.failed,1);
assert.throws(()=>m.normalize([initial,initial]),/duplicadas/);
assert.throws(()=>m.save(proposal,{status:'proposed',evidenceKey:'missing'},[]),/evidencia/);
const state=JSON.parse(JSON.stringify({mitigationActions:[applied]}));
assert.equal(m.normalize(state.mitigationActions)[0].status,'applied');
const app=fs.readFileSync('js/app.js','utf8'),html=fs.readFileSync('index.html','utf8');
assert(app.includes('renderMitigationActions')&&app.includes('mitigationOverview'));
assert(app.includes('data-mitigation-verify')&&app.includes('data-mitigation-check-field'));
assert(app.includes('data-pdf-appendix-save')&&app.includes('data-remove-evidence-photo'));
assert(app.includes('renderResidualAssessment')&&app.includes('renderMitigationDashboard')&&app.includes('data-save-residual'));
assert(app.includes('record.residualAssessments = mitigation.normalizeResidual(item.residualAssessments)'));
assert(html.includes('js/audit-mitigation.js'));
console.log('PASS mitigation plans, approvals, controlled transitions, JSON roundtrip and display');
